'use strict';

// Generates src/utils/components/DynamicPfIcon/iconLoaders.generated.ts

const { mkdirSync, writeFileSync } = require('node:fs');
const { dirname, resolve } = require('node:path');

const moduleMap = require('@patternfly/react-icons/dist/dynamic-modules.json');

const icons = new Map();

for (const [exportName, modulePath] of Object.entries(moduleMap)) {
  const match = /^dist\/dynamic\/icons\/(.+)-icon$/.exec(modulePath);

  if (exportName.endsWith('Icon') && match) {
    icons.set(match[1], `@patternfly/react-icons/${modulePath}`);
  }
}

if (icons.size === 0) {
  throw new Error('No PatternFly icons found. Check dynamic-modules.json format.');
}

const entries = [...icons.entries()]
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(
    ([name, modulePath]) =>
      `  ${JSON.stringify(name)}: () => import(${JSON.stringify(modulePath)}),`,
  )
  .join('\n');

const output = resolve(__dirname, '../src/utils/components/DynamicPfIcon/iconLoaders.generated.ts');

mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `// Generated by scripts/generate-pf-icon-loaders.cjs. Do not edit manually.
/* eslint-disable @typescript-eslint/naming-convention, max-lines */

import type { ComponentType } from 'react';

type IconLoader = () => Promise<{ default: ComponentType }>;

const iconLoaders: Partial<Record<string, IconLoader>> = {
${entries}
};

export default iconLoaders;
`,
);

console.log(`Generated ${icons.size} PatternFly icon loaders: ${output}`);
